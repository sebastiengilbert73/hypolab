"""Core Pydantic schemas for dataset profiling, hypotheses, experiments, and reports."""

from __future__ import annotations

from enum import Enum
from typing import Any
from pydantic import BaseModel, Field


class DistributionType(str, Enum):
    NORMAL = "normal"
    SKEWED = "skewed"
    BIMODAL_OR_MULTIMODAL = "multimodal"
    UNIFORM = "uniform"
    CATEGORICAL = "categorical"
    BINARY = "binary"
    TEMPORAL = "temporal"
    CONSTANT = "constant"
    IDENTIFIER = "identifier"


class ColumnProfile(BaseModel):
    """Statistical profile of a single column."""

    name: str
    dtype: str
    semantic_type: str = Field(
        description="High-level type: numeric, categorical, boolean, datetime, text, identifier"
    )
    count: int
    missing_count: int
    missing_pct: float
    unique_count: int
    distribution_type: DistributionType
    mean: float | None = None
    std: float | None = None
    min: float | str | None = None
    q25: float | None = None
    median: float | None = None
    q75: float | None = None
    max: float | str | None = None
    skewness: float | None = None
    kurtosis: float | None = None
    outlier_count_iqr: int = 0
    top_categories: dict[str, int] = Field(default_factory=dict)
    sample_values: list[Any] = Field(default_factory=list)


class CorrelationPair(BaseModel):
    """Pairwise correlation summary between two numeric variables."""

    col_a: str
    col_b: str
    pearson_r: float
    spearman_rho: float
    abs_max: float


class QualityAlert(BaseModel):
    """Data quality issue or structural anomaly detected during profiling."""

    severity: str = Field(description="INFO, WARNING, or CRITICAL")
    column: str | None = None
    issue_type: str
    description: str


class DatasetProfile(BaseModel):
    """Complete compact statistical profile of a dataset."""

    dataset_name: str
    row_count: int
    column_count: int
    duplicate_row_count: int
    memory_bytes: int
    columns: list[ColumnProfile]
    top_correlations: list[CorrelationPair] = Field(default_factory=list)
    quality_alerts: list[QualityAlert] = Field(default_factory=list)

    def to_llm_summary(self) -> str:
        """Render a token-efficient summary for LLM consumption."""
        lines = [
            f"Dataset: {self.dataset_name} ({self.row_count:,} rows x {self.column_count} columns, duplicates={self.duplicate_row_count})",
            "\nColumns:",
        ]
        for col in self.columns:
            base = (
                f"- {col.name} [{col.semantic_type} / {col.distribution_type.value}]: "
                f"unique={col.unique_count}, missing={col.missing_pct:.1f}%"
            )
            if col.mean is not None and col.std is not None:
                base += (
                    f", mean={col.mean:.3g}, std={col.std:.3g}, "
                    f"median={col.median:.3g}, IQR=[{col.q25:.3g}, {col.q75:.3g}], "
                    f"min={col.min:.3g}, max={col.max:.3g}, skew={col.skewness or 0.0:.2f}, outliers={col.outlier_count_iqr}"
                )
            elif col.top_categories:
                top_str = ", ".join(f"{k}:{v}" for k, v in list(col.top_categories.items())[:5])
                base += f", top_values={{ {top_str} }}"
            lines.append(base)

        if self.top_correlations:
            lines.append("\nTop Numeric Correlations (Pearson r / Spearman rho):")
            for pair in self.top_correlations[:10]:
                lines.append(
                    f"- {pair.col_a} <-> {pair.col_b}: r={pair.pearson_r:.3f}, rho={pair.spearman_rho:.3f}"
                )

        if self.quality_alerts:
            lines.append("\nQuality Alerts:")
            for alert in self.quality_alerts:
                col_prefix = f"[{alert.column}] " if alert.column else ""
                lines.append(f"- ({alert.severity}) {col_prefix}{alert.issue_type}: {alert.description}")

        return "\n".join(lines)


class ProposedMethod(str, Enum):
    COMPARE_TWO_GROUPS = "compare_two_groups"
    COMPARE_MULTIPLE_GROUPS = "compare_multiple_groups"
    CATEGORICAL_ASSOCIATION = "test_categorical_association"
    CORRELATION_TEST = "test_correlation"
    MULTIVARIATE_REGRESSION = "multivariate_regression"
    PYTHON_SANDBOX = "python_sandbox"


class Hypothesis(BaseModel):
    """A falsifiable scientific hypothesis generated by the Theorist agent."""

    id: str = Field(description="Unique identifier, e.g., HYP-001")
    title: str = Field(description="Short concise title of the hypothesis")
    statement: str = Field(description="Alternative hypothesis (H1) stated clearly")
    null_hypothesis: str = Field(description="Null hypothesis (H0) to be tested/refuted")
    rationale: str = Field(description="Why this hypothesis is worth investigating based on the data profile")
    variables: list[str] = Field(description="Primary columns involved (e.g. [group_col, target_col])")
    confounders: list[str] = Field(default_factory=list, description="Potential confounding columns to control for")
    proposed_method: ProposedMethod = Field(description="Primary test tool or sandbox execution")
    tool_params: dict[str, Any] = Field(
        default_factory=dict,
        description="Arguments for the statistical tool or instructions for the sandbox",
    )
    priority: int = Field(default=1, ge=1, le=5, description="Priority from 1 (highest) to 5 (lowest)")


class ConclusionStatus(str, Enum):
    VALIDATED = "VALIDATED"
    REFUTED = "REFUTED"
    INCONCLUSIVE = "INCONCLUSIVE"


class ExperimentResult(BaseModel):
    """Quantitative outcome of testing a single hypothesis."""

    hypothesis_id: str
    test_used: str
    statistic_name: str = "stat"
    statistic_value: float | None = None
    p_value: float | None = None
    adjusted_p_value: float | None = None
    effect_size_name: str = "effect_size"
    effect_size: float | None = None
    confidence_interval: tuple[float, float] | None = None
    sample_size: int = 0
    conclusion: ConclusionStatus = ConclusionStatus.INCONCLUSIVE
    interpretation: str = ""
    critic_notes: str = ""
    code_executed: str = ""
    additional_metrics: dict[str, Any] = Field(default_factory=dict)
    figure_json: str | None = None
    error_message: str | None = None


class ScientificReport(BaseModel):
    """Final synthesized report from an autonomous research session."""

    dataset_profile: DatasetProfile
    research_goal: str
    alpha: float
    hypotheses: list[Hypothesis]
    results: list[ExperimentResult]
    executive_summary: str
    methodology_notes: str
    limitations_and_next_steps: list[str] = Field(default_factory=list)
